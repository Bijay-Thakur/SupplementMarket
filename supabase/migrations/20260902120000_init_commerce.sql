create or replace function public.products_search_document()
returns trigger language plpgsql as $$
begin
  new.search_document :=
    setweight(to_tsvector('simple', coalesce(new.name, '')), 'A') ||
    setweight(to_tsvector('simple', coalesce(new.sku, '') || ' ' || coalesce(new.upc, '')), 'A') ||
    setweight(to_tsvector('simple', coalesce(new.search_aliases, '')), 'B') ||
    setweight(to_tsvector('simple', coalesce(new.ingredient_highlights, '')), 'C') ||
    setweight(to_tsvector('simple', coalesce(new.short_description, '')), 'D');
  return new;
end;
$$;

drop trigger if exists trg_products_search on public.products;
create trigger trg_products_search
before insert or update on public.products
for each row execute function public.products_search_document();

create index if not exists products_search_idx on public.products using gin (search_document);
create index if not exists products_name_trgm on public.products using gin (name gin_trgm_ops);
create index if not exists products_sku_trgm on public.products using gin (sku gin_trgm_ops);
