create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  base text;
  uname text;
  n int := 0;
begin
  base := lower(regexp_replace(split_part(coalesce(new.email, 'user'), '@', 1), '[^a-z0-9]+', '', 'g'));
  if length(base) < 3 then base := 'user'; end if;
  uname := base;
  while exists (select 1 from public.profiles where username = uname) loop
    n := n + 1;
    uname := base || n::text;
  end loop;
  insert into public.profiles (id, username, display_name, first_name, last_name, profile_completed)
  values (
    new.id,
    uname,
    coalesce(new.raw_user_meta_data->>'full_name', uname),
    coalesce(new.raw_user_meta_data->>'given_name', ''),
    coalesce(new.raw_user_meta_data->>'family_name', ''),
    false
  );
  insert into public.user_roles (user_id, role) values (new.id, 'customer');
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.prevent_role_escalation()
returns trigger language plpgsql as $$
begin
  if tg_op = 'UPDATE' and new.role is distinct from old.role then
    if auth.role() is distinct from 'service_role' then
      raise exception 'Role changes require a privileged migration or service-role script';
    end if;
  end if;
  if tg_op = 'INSERT' and new.role = 'admin' and auth.role() is distinct from 'service_role' then
    raise exception 'Admin bootstrap requires a privileged migration or service-role script';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_user_roles_no_escalation on public.user_roles;
create trigger trg_user_roles_no_escalation
before insert or update on public.user_roles
for each row execute function public.prevent_role_escalation();

